NOTE = "<p><small>아래 사례와 예문은 설명을 위해 만든 것입니다.</small></p>"


def CASES(hid, h2, cases):
    out = '<h2 id="%s">%s</h2>%s' % (hid, h2, NOTE)
    for t, x in cases:
        out += "<h3>%s</h3><p>%s</p>" % (t, x)
    return out


def FIX(hid, h2, pairs, tail):
    out = '<h2 id="%s">%s</h2>' % (hid, h2)
    for b, a in pairs:
        out += "<blockquote><p><b>고치기 전</b> %s</p><p><b>고친 뒤</b> %s</p></blockquote>" % (b, a)
    return out + "<p>%s</p>" % tail


